class InverseFourierSpectralTransform:
    """
    Inverse FFT transform class for hyperspectral data transformed with real+imag FFT.
    """
    def __init__(self, 
                 norm: str = 'realimag',
                 channel_first: bool = True, 
                 device: str = 'cpu', 
                 shift: bool = True, 
                 stack_type: str = 'alternate'):
        self.channel_first = channel_first
        self.norm = norm
        self.device = device
        self.shift = shift
        self.stack_type = stack_type

    def __call__(self, cube: torch.Tensor) -> torch.Tensor:
        """
        Apply inverse FFT transform to a single cube.

        Args:
            cube (torch.Tensor): Input real+imag transformed tensor (2C, H, W) or (H, W, 2C)

        Returns:
            torch.Tensor: Reconstructed real-valued tensor.
        """
        return inverse_fft_from_real_imag(
            y_transformed=cube,
            norm=self.norm,
            device=self.device,
            channel_first=self.channel_first,
            shift=self.shift,
            stack_type=self.stack_type
        )

    def __str__(self):
        return f"InverseFourierSpectralTransform(norm={self.norm}, device={self.device})"