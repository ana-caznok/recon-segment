import torch

def inverse_fft_from_real_imag(
    y_transformed: torch.Tensor,
    norm: str = 'realimag',
    device: str = 'cpu',
    channel_first: bool = True,
    shift: bool = True,
    stack_type: str = 'alternate'
) -> torch.Tensor:
    """
    Reconstructs the original input from the FFT output generated by fft_real_imag_normalized.

    Args:
        y_transformed (torch.Tensor): Real+imag FFT output tensor (shape: (2C, H, W) or (H, W, 2C)).
        norm (str): Normalization used in FFT: 'realimag', 'softmax', or 'none'.
        device (str): Device for computation ('cpu' or 'cuda').
        channel_first (bool): Whether channels are the first axis.
        shift (bool): If True, applies ifftshift before inverse FFT.
        stack_type (str): 'alternate' for interleaved real/imag, else stacked format.

    Returns:
        torch.Tensor: Reconstructed real-valued tensor (same shape as original input).
    """
    # Spectral (channel) axis
    dim = 0 if channel_first else -1

    # Recover number of original spectral channels
    C = y_transformed.shape[dim] // 2

    # Ensure tensor is on the correct device
    x_tensor = y_transformed.to(device)

    # Split into real and imaginary components
    if stack_type == 'alternate':
        if channel_first:
            real = x_tensor[0::2]
            imag = x_tensor[1::2]
        else:
            real = x_tensor[..., 0::2]
            imag = x_tensor[..., 1::2]
    else:
        real, imag = torch.tensor_split(x_tensor, 2, dim=dim)

    # Combine into complex tensor
    complex_tensor = torch.complex(real, imag)

    # Undo FFT shift if applied during forward FFT
    if shift:
        complex_tensor = torch.fft.ifftshift(complex_tensor, dim=dim)

    # Perform inverse FFT along spectral dimension
    ifft_result = torch.fft.ifft(complex_tensor, dim=dim)

    # Return only real part (original data is real)
    return ifft_result.real

